"""Replik (party-leader debate topics): prepare, select, final, export.

    python -m ml.experiments.debates prepare|select|final|export [--deadline-minutes N]

The champion is the published SBERT pipeline (speaker centring, UMAP 5-D n30, HDBSCAN eom 150/25)
refitted on the evaluation side without consensus or noise reassignment
(configs/experiments/debates.yaml). Registry decisions never change Replik's published files.
"""
from __future__ import annotations

import argparse
import json

import numpy as np

from ml.cluster_lab.io import atomic_json, now
from . import accept, contract, fit, runtime
from . import debates_data as data
from . import debates_select as sel
from .registry import Registry

FOLDER = data.FOLDER
QUESTION = ('Which subjects do Swedish party leaders speak about in the party-leader debates, '
            'grouped by topic similarity (not by opinion)?')
CORPUS = ('Riksdag party-leader debates 1993-2026 (108 debates, 10,148 speeches), passages of whole '
          'sentences closed at 80 words (min 40, max 150); public parliamentary record')
EVAL_SEEDS = [10, 11, 12, 13, 14]
# Chosen on the selection side (docs/cluster-experiments-debates.md, "Selection").
RUNS = {
    'champion': ('sbert-speaker', 'hdbscan-150-25'),
    'sbert-party': ('sbert-party', 'hdbscan-150-25'),
    'sbert-speaker-kmeans': ('sbert-speaker', 'kmeans-30'),
    'minilm-speaker': ('minilm-speaker', 'hdbscan-150-25'),
}
LIMITATIONS = [
    'Topic similarity is not opinion similarity: a group says passages talk about a similar subject, '
    'not that speakers agree.',
    'Refitted on the evaluation half of the debates (whole debates), without the published consensus, '
    'merge and noise-reassignment steps and without the 10% largest-group cap (not supported by '
    'ml/experiments/fit.cluster).',
    'Group terms are generated by c-TF-IDF and unreviewed.',
]


def pipeline(rep_name: str, clustering: str) -> dict:
    text_key, model_key, centring = sel.REPRESENTATIONS[rep_name]
    rule = 'speakers with >= 5 passages in >= 2 debates' if centring == 'speaker' else 'every group'
    return {'text': {'version': data.TEXT_VERSIONS[text_key], 'unit': 'sentences closed at 80 words',
                     'masking': text_key == 'masked'},
            'embedding': dict(sel.MODELS[model_key]),
            'representation': {'kind': 'raw'} if centring == 'none' else
            {'kind': 'centred', 'groups': centring, 'rule': rule},
            'reduction': dict(sel.REDUCTION), 'clustering': dict(sel.CLUSTERINGS[clustering]),
            'map': '2-D UMAP of the representation (15 neighbours, min_dist 0.1, seed 10)'}


def evaluation_side():
    obs = data.load()
    return obs[~obs.selection].reset_index(drop=True)


def final(deadline) -> dict:
    obs = evaluation_side()
    marks = runtime.Checkpoints(FOLDER / 'final')
    dataset = data.dataset_version(obs)
    confounders = {'party': obs.party.to_numpy(), 'speaker': obs.speaker.to_numpy(),
                   'debate': obs.debate_id.to_numpy()}
    for label, (rep_name, clustering) in RUNS.items():
        if marks.done(label) or deadline.expired():
            continue
        pipe = pipeline(rep_name, clustering)
        with runtime.measure() as res:
            rep = sel.representation(obs, rep_name, deadline)
            # Centring is already applied with the champion's rule, so fit only normalises ('raw').
            labels, _, metrics = fit.evaluate_candidate(
                rep, {**pipe, 'representation': {'kind': 'raw'}}, EVAL_SEEDS, confounders)
            metrics['time'] = sel.time_coverage(labels, obs.decade.to_numpy())
        np.save(FOLDER / 'final' / f'{label}-labels.npy', labels)
        run = {'domain': 'debates', 'question': QUESTION, 'corpus': CORPUS, 'label': label,
               'sample': {'side': 'evaluation', 'observations': len(obs), 'debates': int(obs.debate_id.nunique())},
               'dataset_version': dataset, 'pipeline': pipe, 'seeds': EVAL_SEEDS, 'role': 'evaluation',
               'metrics': metrics, 'resources': res, 'limitations': LIMITATIONS, 'created_at': now()}
        run['run_id'] = contract.run_id('debates', dataset, pipe, EVAL_SEEDS, 'evaluation')
        marks.put(label, run)
    return decide(marks)


def decide(marks) -> dict:
    runs = {k: v for k, v in marks.all().items() if k in RUNS}
    if 'champion' not in runs:
        return {'note': 'champion not fitted yet'}
    reg = Registry('debates')
    rules, sha = accept.criteria('debates')
    champ = runs['champion']
    reg.register(champ, 'champion', 'published pipeline refitted under the protocol, no consensus')
    out, promoted = {}, any(h['action'] == 'promote' for h in reg.load()['history'])
    # Every candidate is judged against the refitted champion. At most one is promoted: the first
    # that passes in RUNS order (ordered by how small a change it is from the champion).
    for label in RUNS:
        run = runs.get(label)
        if label == 'champion' or run is None:
            continue
        entry = reg.register(run, 'candidate', 'chosen on the selection side')
        if entry['status'] == 'candidate' and 'acceptance' not in entry:
            report = accept.check(run, champ, rules, sha)
            status = reg.decide(run['run_id'], report)
            if report['passed'] and not promoted:
                reg.promote(run['run_id'], 'passed every frozen criterion (registry only; Replik unchanged)')
                status, promoted = 'champion', True
            out[label] = {'status': status, 'failed': report['failed']}
        else:
            out[label] = {'status': entry['status'], 'failed': entry.get('acceptance', {}).get('failed')}
    atomic_json(FOLDER / 'decision.json', out)
    return out


def main() -> None:
    parser = argparse.ArgumentParser(prog='python -m ml.experiments.debates')
    parser.add_argument('command', choices=('prepare', 'select', 'final', 'export'))
    parser.add_argument('--deadline-minutes', type=float)
    args = parser.parse_args()
    deadline = runtime.Deadline(args.deadline_minutes, margin_minutes=5 if args.deadline_minutes else 30)
    if args.command == 'prepare':
        summary = data.prepare()
        atomic_json(FOLDER / 'prepare.json', summary)
        print(json.dumps({k: summary[k] for k in ('observations', 'dataset_version', 'sides', 'masking')}, indent=1))
        return
    with runtime.heavy(wait_seconds=3600):
        if args.command == 'select':
            results = sel.run(FOLDER, deadline)
            frame = sel.table(results)
            frame.to_csv(FOLDER / 'select.csv', index=False)
            print(frame.round(3).to_string(index=False))
        elif args.command == 'final':
            print(json.dumps(final(deadline), indent=1))
        else:
            from .debates_export import export_all
            print(json.dumps(export_all(deadline), indent=1))


if __name__ == '__main__':
    main()
