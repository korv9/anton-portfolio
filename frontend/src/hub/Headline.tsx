/**
 * The hub's headline: the size of the dbt project in three figures, the newest ingestion run on a
 * line under them, and the files they come from with their dates. The full picture is the flow further
 * down (PlatformFlow.tsx). A figure whose file cannot be read, or that has no date, is left out.
 */
import { useEffect, useState } from 'react'
import { deliveryState } from '../dataSource'
import { l } from '../i18n'
import { loadStatus } from '../meaning/freshness'
import { ago, day, num, ok, useFile } from '../tech/techData'
import { readStatus, type Status } from './platformStatus'

/** The dbt project's size, from the schema export (platform/publish/export_schema.py). */
export type Summary = {
  models: number
  tests: number
  sources: number
  rows: number
  generated_at?: string
  /** When the file was regenerated by hand and committed (f239becd, PR #152), before the export
   * wrote generated_at; the next export replaces it. */
  committed_at?: string
}

export function useStatus() {
  const [status, setStatus] = useState<ReturnType<typeof readStatus>>(null)
  useEffect(() => {
    loadStatus().then((s) => setStatus(s && readStatus(s as Status)))
  }, [])
  return status
}

/** The time the active R2 release was published, once the delivery manifest is read. */
export function useRelease() {
  const [release, setRelease] = useState<string>()
  useEffect(() => {
    deliveryState().then(
      (d) => setRelease(d.activatedAt ?? undefined),
      () => undefined,
    )
  }, [])
  return release
}

/**
 * The dbt project's size with its date: the file's own generated_at, the release it came in, or
 * the commit that regenerated it. Without any of them the figures are left out.
 */
export function useDbtSize() {
  const summary = useFile<Summary>('schema/summary.json')
  const release = useRelease()
  const at = ok(summary)
    ? (summary.generated_at ?? release ?? summary.committed_at)
    : undefined
  const how = !ok(summary)
    ? ''
    : summary.generated_at
      ? l('built', 'byggd')
      : release
        ? l('in the release of', 'i releasen från')
        : l('committed', 'committad')
  return ok(summary) && at ? { size: summary, at, how, release } : { release }
}

export default function Headline() {
  const { size, at, how } = useDbtSize()
  const status = useStatus()
  const figures: [string, string][] = []
  if (size)
    figures.push(
      [l('dbt models', 'dbt-modeller'), num(size.models)],
      [l('dbt tests', 'dbt-tester'), num(size.tests)],
      [l('dbt source tables', 'dbt-källtabeller'), num(size.sources)],
    )
  if (!figures.length && !status) return null
  const files = [
    size && at && `schema/summary.json · ${how} ${day(at)} UTC`,
    status && `status/ingestion.json · ${day(status.last.recorded_at)} UTC`,
  ].filter(Boolean)
  return (
    <section
      id="projects-overview"
      className="hub-headline"
      aria-label={l('The platform in figures', 'Plattformen i siffror')}
    >
      {figures.length > 0 && (
        <dl>
          {figures.map(([label, value]) => (
            <div key={label}>
              <dt>{label}</dt>
              <dd>{value}</dd>
            </div>
          ))}
        </dl>
      )}
      {status && (
        <p className="hub-headline-run">
          {l('Last ingestion run', 'Senaste inläsning')}{' '}
          <strong>{ago(status.last.recorded_at!)}</strong>
        </p>
      )}
      <p className="tech-meta">{files.join(' · ')}</p>
    </section>
  )
}
